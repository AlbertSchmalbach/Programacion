# Valor absoluto : abs()
numero = -10
valor_absoluto = abs(numero)
print(f"Valor absoluto: {valor_absoluto}")

# Potenciación: pow(base, exponente)
base = 2
exponente = 3
resultado = pow(base, exponente)
print(f"Potenciacion: {resultado}")

# Redondeo: round(numero, decimales)
numero = 3.14159265
redondeo = round(numero,2)
print(f"Redondeo: {redondeo}")

# Máximo y Mínimo: max(iterable) y min(iterable)
numeros = [5, 10, 2, 8]
maximo = max(numeros)
minimo = min(numeros)
print(f"Maximo: {maximo}")
print(f"Minimo: {minimo}")

# El Módulo de Matemáticas
import math

# Raíz cuadrada: math.sqrt(numero)
numero = 16
raiz_cuadrada = math.sqrt(numero)
print(f"Raiz: {raiz_cuadrada}")

# Logaritmo natural: math.log(numero)
numero = 2.71828
logaritmo = math.log(numero)
print(f"Log: {logaritmo}")

# Función exponencial: math.exp(numero)
numero = 1.0
exponencial = math.exp(numero)
print(f"Exponencial: {exponencial}")

# Trigonometría: math.sin(angulo), math.cos(angulo), math.tan(angulo)
angulo = 45  # Ángulo en grados
seno = math.sin(angulo)
coseno = math.cos(angulo)
tangente = math.tan(angulo)
print(f"Sen: {seno}, Cos: {coseno}, Tan: {tangente}")

# Constantes matemáticas: math.pi y math.e
pi = math.pi
euler = math.e
print(f"PI: {pi}, Euler: {euler}")